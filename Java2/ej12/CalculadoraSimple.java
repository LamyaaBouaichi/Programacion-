public class CalculadoraSimple {

    public static void main (String[] args) {

        int n1 = 18;
        int n2 = 3;
	int resultado;

	resultado = n1 + n2;
	System.out.println("Suma: " + n1 + " + " + n2 + " = " + resultado);
	resultado = n1 - n2;
	System.out.println("Resta : " + n1 + " - " + n2 + " = " + resultado);
	resultado = n1 * n2;
	System.out.println("Multiplicación : " + n1 + " * " + n2 + " = " + resultado);
	resultado = n1 / n2;
	System.out.println("Suma: " + n1 + " / " + n2 + " = " + resultado);
        
	}
}